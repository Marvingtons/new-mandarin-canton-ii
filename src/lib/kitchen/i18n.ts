/**
 * The staff area's own tiny i18n: 中文 (Traditional) and English.
 *
 * KITCHEN ONLY. The customer site has its own dictionary (lib/i18n) with its
 * own locales, and nothing here touches it. Every piece of UI chrome under
 * components/kitchen and app/[kitchenSlug] reads its words from THIS file
 * through t(); `npm run verify:kitchen-i18n` fails on a raw string literal
 * there, on a key missing from either language, and on an em dash.
 *
 * DISH NAMES ARE NOT HERE, ON PURPOSE. A dish always renders both names, 中文
 * large and English small, whatever the toggle says: the person taking the
 * order and the person cooking it may read different ones. Those come from the
 * menu data, never from t().
 *
 * Placeholders are `{name}`, replaced by kt(). A missing variable renders as
 * the bare placeholder rather than "undefined", so a slip is visible.
 */

export const KITCHEN_LANGS = ["zh-Hant", "en"] as const;
export type KitchenLang = (typeof KITCHEN_LANGS)[number];

/** TODO(confirm): default language for a tablet that has never chosen one. */
export const DEFAULT_KITCHEN_LANG: KitchenLang = "zh-Hant";

/** Mirrors the localStorage choice so the server renders it first time. */
export const KITCHEN_LANG_COOKIE = "nmc_kitchen_lang";
/** The per-device preference itself. */
export const KITCHEN_LANG_STORAGE_KEY = "nmc-kitchen-lang";

export function isKitchenLang(value: unknown): value is KitchenLang {
  return typeof value === "string" && (KITCHEN_LANGS as readonly string[]).includes(value);
}

export function toKitchenLang(value: unknown): KitchenLang {
  return isKitchenLang(value) ? value : DEFAULT_KITCHEN_LANG;
}

