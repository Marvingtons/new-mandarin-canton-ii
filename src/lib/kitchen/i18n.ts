export const KITCHEN_DICTIONARIES: Record<KitchenLang, Record<KitchenKey, string>> = {
  "zh-Hant": zhHant,
  en,
};

export type KitchenVars = Record<string, string | number>;

/** Look a key up in a language, filling `{placeholders}`. Pure; server or client. */
export function kt(lang: KitchenLang, key: KitchenKey, vars?: KitchenVars): string {
  const template = KITCHEN_DICTIONARIES[lang][key] ?? KITCHEN_DICTIONARIES[DEFAULT_KITCHEN_LANG][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}

export type KitchenT = (key: KitchenKey, vars?: KitchenVars) => string;
